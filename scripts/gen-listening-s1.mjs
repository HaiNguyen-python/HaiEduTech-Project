const staffLabels = ["Receptionist", "Assistant", "Agent", "Adviser", "Officer"];

function buildSet(t, i) {
  const staff = staffLabels[i % staffLabels.length];
  const midSpoken = t.phoneMid[0] === t.phoneMid[1]
    ? `double-${numWords(t.phoneMid[0])}`
    : spellDigits(t.phoneMid);
  const feeSpoken = `${numWords(t.fee)} pounds`;
  const transcript = [
    `${staff}: Good morning, ${t.org}. How can I help you today?`,
    `Caller: Hello. I'd like to ${t.purpose}, please.`,
    `${staff}: Of course. Could I start with your full name?`,
    `Caller: Yes, it's ${t.first} ${t.surname}. That's ${spell(t.surname)}.`,
    `${staff}: Thank you. And your date of birth?`,
    `Caller: The ${dayWords(t.day)} of ${t.month}, ${yearWords(t.year)}.`,
    `${staff}: We have three options - ${t.plans[0]}, ${t.plans[1]} and ${t.plans[2]}. Which would suit you best?`,
    `Caller: I'll take the ${t.chosen} option, please. What exactly does that include?`,
    `${staff}: With the ${t.chosen} option you get ${numWords(t.num)} ${t.numUnit}, and ${t.inc[0]}. The ${t.feeLabel} is ${feeSpoken}.`,
    `Caller: That sounds reasonable, thank you.`,
    `${staff}: Could I take your address as well?`,
    `Caller: It's ${t.houseNo} ${t.street} Road. The postcode is ${spellPostcode(t.postcode)}.`,
    `${staff}: And the best mobile number to reach you on?`,
    `Caller: It's ${spellDigits(t.phoneLead)}, ${midSpoken}, ${spellDigits(t.phoneTail)}.`,
    `${staff}: Lovely. Is there anything else before I confirm everything?`,
    `Caller: Yes - could you also put me down for the ${t.extra[0]}?`,
    `${staff}: That's all done. I'll email your confirmation this afternoon.`,
  ];

  const formLayout = [
    "APPLICANT",
    `  First name:            ${t.first}`,
    "  Surname:               {1}",
    `  Date of birth:         ${t.day} ${t.month} {2}`,
    "",
    "BOOKING DETAILS",
    "  Option chosen:         {3}",
    `  ${t.numLabel}:${" ".repeat(Math.max(1, 22 - t.numLabel.length))}{4}`,
    "  Price / fee:           £ {5}",
    "  Also included:         {10}",
    "",
    "CONTACT",
    `  Address:               ${t.houseNo} {6} Road`,
    "  Postcode:              {7}",
    `  Mobile:                ${t.phoneLead} {8} ${t.phoneTail}`,
    "",
    "EXTRAS",
    "  Additional item:       {9}",
  ].join("\n");

  const questions = [
    { prompt: "Surname: ___", answer: t.surname, maxWords: 1 },
    { prompt: `Date of birth: ${t.day} ${t.month} ___`, answer: String(t.year), maxWords: 1 },
    { prompt: "Option chosen: ___", answer: t.chosen, maxWords: 2 },
    { prompt: t.numQ, answer: String(t.num), maxWords: 1 },
    { prompt: `${t.feeLabel}: £___`, answer: String(t.fee), maxWords: 1 },
    { prompt: `Address: ${t.houseNo} ___ Road`, answer: t.street, maxWords: 1 },
    { prompt: "Postcode: ___", answer: t.postcode, maxWords: 2 },
    { prompt: `Mobile: ${t.phoneLead} ___ ${t.phoneTail}`, answer: t.phoneMid, maxWords: 1 },
    { prompt: t.extra[2], answer: t.extra[1], maxWords: 2 },
    { prompt: t.inc[2], answer: t.inc[1], maxWords: 2 },
  ];

  return `  {
    id: ${q(t.id)},
    section: 1,
    questionType: "Form / Note Completion",
    questionTypeVi: "Điền form / ghi chú",
    title: ${q(t.title)},
    titleVi: ${q(t.titleVi)},
    context: ${q(`You will hear a telephone conversation with ${t.org}. Complete the form below. Write NO MORE THAN TWO WORDS AND/OR A NUMBER for each answer.`)},
    contextVi: ${q(`Bạn sẽ nghe cuộc gọi với ${t.org}. Hoàn thành form bên dưới. Viết KHÔNG QUÁ HAI TỪ VÀ/HOẶC MỘT SỐ cho mỗi đáp án.`)},
    transcript:
${transcriptLiteral(transcript)},
    rate: 0.85,
    formTitle: ${q(`${t.org.toUpperCase()} - BOOKING FORM`)},
    formLayout:
${transcriptLiteral(formLayout.split("\n"))},
    questions: [
${questions.map(qq => `      { type: "fill-in", prompt: ${q(qq.prompt)}, answer: ${q(qq.answer)}, maxWords: ${qq.maxWords} },`).join("\n")}
    ],
  },`;
}

const body = topics.map(buildSet).join("\n\n");
