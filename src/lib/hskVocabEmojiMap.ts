function stableIndex(value: string, size: number): number {
  let hash = 0;
  for (const char of value) hash = (hash * 31 + (char.codePointAt(0) ?? 0)) >>> 0;
  return hash % size;
}

/** Resolve a varied, stable visual for one Chinese word. */
export function resolveHskVocabEmoji(hanzi: string, englishDefinition: string, category?: string): string {
  const exact = HANZI_EMOJI[hanzi];
  if (exact) return exact;

  const shared = resolveVocabEmoji(englishDefinition, category);
  const sharedFallback = category ? categoryEmojiMap[category] : undefined;
  if (shared !== "📖" && shared !== sharedFallback) return shared;

  const pool = category ? CATEGORY_POOLS[category] : undefined;
  if (pool?.length) return pool[stableIndex(hanzi, pool.length)];

  const general = ["🔹", "🔸", "🔶", "🔷", "⭐", "💡", "🎯", "🧩", "📌", "🔑", "💬", "✨"];
  return general[stableIndex(hanzi, general.length)];
}