// Quick lookup helpers
export const UNIVERSITY_COUNTRIES = Array.from(new Set(UNIVERSITIES.map(u => u.country))).sort();

export function findUniversityByName(query: string): University | null {
  const q = query.trim().toLowerCase();
  if (!q) return null;
  return UNIVERSITIES.find(u => u.name.toLowerCase().includes(q) || u.id === q) || null;
}
