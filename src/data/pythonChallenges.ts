export const getChallengeById = (id: string) => pythonChallenges.find(c => c.id === id);
export const getNextChallenge = (id: string) => {
  const idx = pythonChallenges.findIndex(c => c.id === id);
  return idx >= 0 && idx < pythonChallenges.length - 1 ? pythonChallenges[idx + 1] : null;
};
export const getPrevChallenge = (id: string) => {
  const idx = pythonChallenges.findIndex(c => c.id === id);
  return idx > 0 ? pythonChallenges[idx - 1] : null;
};
